-- Replace policies from the earlier draft (especially the overly broad message-read policy).
drop policy if exists "Profiles are readable by signed-in members" on public.profiles;
drop policy if exists "Users can create their own profile" on public.profiles;
drop policy if exists "Users can update their own profile" on public.profiles;
drop policy if exists "Members can read messages" on public.messages;
drop policy if exists "Members can send as themselves" on public.messages;
drop policy if exists "Users can delete their own messages" on public.messages;
drop policy if exists "Members can see giveaway entries" on public.giveaway_entries;
drop policy if exists "Members can enter once" on public.giveaway_entries;
drop policy if exists "Users can remove their own entry" on public.giveaway_entries;
drop policy if exists "Members can read giveaway deadline" on public.giveaway_config;
drop policy if exists "friend_requests_read_related" on public.friend_requests;
drop policy if exists "friend_requests_insert_self_pending" on public.friend_requests;
drop policy if exists "friend_requests_recipient_update_status" on public.friend_requests;
drop policy if exists "messages_read_public_or_own_friend_dm" on public.messages;
drop policy if exists "messages_insert_public_or_friend_dm" on public.messages;
drop policy if exists "messages_delete_own" on public.messages;
drop policy if exists "giveaway_config_read_authenticated" on public.giveaway_config;
drop policy if exists "giveaway_entries_read_authenticated" on public.giveaway_entries;
drop policy if exists "giveaway_entries_insert_before_deadline" on public.giveaway_entries;
drop policy if exists "giveaway_entries_delete_own" on public.giveaway_entries;
drop policy if exists "profiles_select_authenticated" on public.profiles;
drop policy if exists "profiles_insert_own" on public.profiles;
drop policy if exists "profiles_update_own" on public.profiles;

create policy "profiles_select_authenticated" on public.profiles for select to authenticated using (true);
create policy "profiles_insert_own" on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "profiles_update_own" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

create policy "friend_requests_read_related" on public.friend_requests
for select to authenticated using (auth.uid() = sender_id or auth.uid() = recipient_id);
create policy "friend_requests_insert_self_pending" on public.friend_requests
for insert to authenticated with check (auth.uid() = sender_id and status = 'pending' and sender_id <> recipient_id);
create policy "friend_requests_recipient_update_status" on public.friend_requests
for update to authenticated using (auth.uid() = recipient_id and status = 'pending')
with check (auth.uid() = recipient_id and status in ('accepted','declined'));
-- Prevent changing sender_id/recipient_id during acceptance; only status can be updated.
revoke update on public.friend_requests from authenticated;
grant update(status) on public.friend_requests to authenticated;

-- This deliberately restricts private messages to accepted friends and both participants.
create policy "messages_read_public_or_own_friend_dm" on public.messages
for select to authenticated using (room = 'public' or public.can_access_dm_room(room));
create policy "messages_insert_public_or_friend_dm" on public.messages
for insert to authenticated with check (
  auth.uid() = user_id and (room = 'public' or public.can_access_dm_room(room))
);
create policy "messages_delete_own" on public.messages
for delete to authenticated using (auth.uid() = user_id);

create policy "giveaway_config_read_authenticated" on public.giveaway_config
for select to authenticated using (true);
create policy "giveaway_entries_read_authenticated" on public.giveaway_entries
for select to authenticated using (true);
create policy "giveaway_entries_insert_before_deadline" on public.giveaway_entries
for insert to authenticated with check (
  auth.uid() = user_id and exists (select 1 from public.giveaway_config gc where gc.id = true and now() < gc.ends_at)
);
create policy "giveaway_entries_delete_own" on public.giveaway_entries
for delete to authenticated using (auth.uid() = user_id);

-- Explicit client grants for Supabase's REST API.
grant select, insert, update on public.profiles to authenticated;
grant select, insert on public.friend_requests to authenticated;
grant select, insert, delete on public.messages to authenticated;
grant select, insert, delete on public.giveaway_entries to authenticated;
grant select on public.giveaway_config to authenticated;

