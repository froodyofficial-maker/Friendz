-- Safe for the earlier Friendz schema: adds friend requests and replaces the overly broad message policies.
-- Never put a service_role/secret key in index.html. The publishable key is intended for browser use with RLS.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (char_length(username) between 2 and 24),
  bio text not null default '' check (char_length(bio) <= 160),
  avatar_url text,
  watching_url text,
  accent_color text,
  created_at timestamptz not null default now()
);

create table if not exists public.friend_requests (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted','declined')),
  created_at timestamptz not null default now(),
  constraint friend_request_not_self check (sender_id <> recipient_id),
  constraint friend_request_pair_unique unique(sender_id, recipient_id)
);
create index if not exists friend_requests_recipient_status_idx on public.friend_requests(recipient_id,status);
create index if not exists friend_requests_sender_status_idx on public.friend_requests(sender_id,status);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  room text not null check (room = 'public' or room like 'dm:%'),
  content text not null check (char_length(content) between 1 and 1000),
  created_at timestamptz not null default now()
);
create index if not exists messages_room_created_idx on public.messages(room, created_at);

create table if not exists public.giveaway_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table if not exists public.giveaway_config (
  id boolean primary key default true check (id = true),
  ends_at timestamptz not null default (now() + interval '5 days')
);
insert into public.giveaway_config (id) values (true) on conflict (id) do nothing;

-- Security-definer helper functions let RLS check accepted friendships without exposing other users' requests.
create or replace function public.are_friends(user_a uuid, user_b uuid)
returns boolean language sql stable security definer set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.friend_requests fr
    where fr.status = 'accepted'
      and ((fr.sender_id = user_a and fr.recipient_id = user_b)
        or (fr.sender_id = user_b and fr.recipient_id = user_a))
  );
$$;

create or replace function public.can_access_dm_room(room_name text)
returns boolean language plpgsql stable security definer set search_path = public, pg_temp
as $$
declare a_text text; b_text text; a_id uuid; b_id uuid;
begin
  if auth.uid() is null or room_name !~ '^dm:[0-9a-fA-F-]{36}:[0-9a-fA-F-]{36}$' then return false; end if;
  a_text := split_part(room_name, ':', 2);
  b_text := split_part(room_name, ':', 3);
  begin a_id := a_text::uuid; b_id := b_text::uuid; exception when others then return false; end;
  if a_id = b_id or room_name <> 'dm:' || least(a_id::text,b_id::text) || ':' || greatest(a_id::text,b_id::text) then return false; end if;
  return (auth.uid() = a_id or auth.uid() = b_id) and public.are_friends(a_id,b_id);
end;
$$;
revoke all on function public.are_friends(uuid,uuid) from public;
revoke all on function public.can_access_dm_room(text) from public;
grant execute on function public.are_friends(uuid,uuid) to authenticated;
grant execute on function public.can_access_dm_room(text) to authenticated;

alter table public.profiles enable row level security;
alter table public.friend_requests enable row level security;
alter table public.messages enable row level security;
alter table public.giveaway_entries enable row level security;
